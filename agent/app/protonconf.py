"""Parse an uploaded Proton VPN ``wg.conf`` and rebuild it from an allow-list.

``wg-quick`` runs hook keys (PostUp, PreDown, ...) as shell commands, so the
uploaded text is never written as-is. Only validated values of allowed keys
are copied into a freshly rendered config. DNS and IPv6 values are dropped
(no resolvconf, no IPv6 in the container). Error messages are German and
never contain key material.
"""

import ipaddress
import re

from . import validate
from .validate import ValidationError

INTERFACE_KEYS = {"privatekey": "PrivateKey", "address": "Address", "mtu": "MTU"}
PEER_KEYS = {"publickey": "PublicKey", "presharedkey": "PresharedKey", "allowedips": "AllowedIPs",
             "endpoint": "Endpoint", "persistentkeepalive": "PersistentKeepalive"}
DEFAULT_KEEPALIVE = 25
# tunnel MTU per profile (0.10.3): a number (1280-1500) or "conf" (the MTU of the uploaded wg.conf). 1340 leaves
# room for WireGuard nested twice over an IPv6 outer path (1500 - 80 - 80); a single tunnel needs 1420.
MTU_MIN, MTU_MAX = 1280, 1500
MTU_DEFAULT = 1340
MTU_AUTO = 1420  # what wg-quick picks on a 1500 link when the config has no MTU
MAX_SIZE = 12 * 1024

_SERVER_RE = re.compile(r"[A-Z]{2}[A-Z0-9-]*#\d+")
_NATPMP_RE = re.compile(r"NAT-PMP.*=\s*(on|off)\s*\Z", re.I)


class ProtonConfig:
    def __init__(self):
        self.private_key = ""
        self.addresses = []  # IPv4 interfaces as str
        self.mtu = None
        self.public_key = ""
        self.preshared_key = ""
        self.allowed_ips = []
        self.endpoint = ""  # host:port
        self.keepalive = DEFAULT_KEEPALIVE
        self.server = ""  # display name, e.g. "CH#12"
        self.natpmp_hint = None  # True/False when the Proton comment says so
        self.removed = []  # names of dropped keys / values (no values of secrets)

    def render(self):
        lines = ["# Generated by portnook from an uploaded Proton config (allow-list)",
                 "[Interface]",
                 "PrivateKey = %s" % self.private_key,
                 "Address = %s" % ", ".join(self.addresses)]
        if self.mtu:
            lines.append("MTU = %d" % self.mtu)
        lines += ["", "[Peer]", "PublicKey = %s" % self.public_key]
        if self.preshared_key:
            lines.append("PresharedKey = %s" % self.preshared_key)
        lines += ["AllowedIPs = %s" % ", ".join(self.allowed_ips),
                  "Endpoint = %s" % self.endpoint]
        if self.keepalive:
            lines.append("PersistentKeepalive = %d" % self.keepalive)
        return "\n".join(lines) + "\n"

    def summary(self):
        """Non-secret description for the UI."""
        return {"server": self.server, "endpoint": self.endpoint, "address": ", ".join(self.addresses),
                "allowed_ips": ", ".join(self.allowed_ips), "natpmp_hint": self.natpmp_hint,
                "removed": list(self.removed)}


def parse(text):
    """Parse and validate ``text``. Returns ``ProtonConfig`` or raises ``ValidationError``."""
    if not isinstance(text, str) or not text.strip():
        raise ValidationError("Die Proton-Konfiguration ist leer.")
    if len(text) > MAX_SIZE:
        raise ValidationError("Die Proton-Konfiguration ist zu gross (max. 12 KiB).")
    text = text.lstrip("﻿")

    cfg = ProtonConfig()
    section = None
    seen_interface = 0
    seen_peer = 0
    values = {"interface": {}, "peer": {}}
    peer_comments = []
    iface_comments = []

    for num, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#") or line.startswith(";"):
            comment = line.lstrip("#; ").strip()
            if section == "peer":
                peer_comments.append(comment)
            else:
                iface_comments.append(comment)
            continue
        if line.startswith("["):
            name = line.strip("[] ").lower()
            if name == "interface":
                seen_interface += 1
                section = "interface"
                if seen_interface > 1:
                    raise ValidationError("Die Konfiguration braucht genau einen [Interface]-Abschnitt.")
            elif name == "peer":
                seen_peer += 1
                section = "peer"
                if seen_peer > 1:
                    raise ValidationError("Die Konfiguration braucht genau einen [Peer]-Abschnitt "
                                          "(mehrere gefunden).")
            else:
                raise ValidationError("Zeile %d: unbekannter Abschnitt [%s]." % (num, line.strip("[] ")[:30]))
            continue
        if "=" not in line:
            raise ValidationError("Zeile %d ist ungültig (erwartet Schlüssel = Wert)." % num)
        key, val = line.split("=", 1)
        key_l = key.strip().lower()
        val = val.split("#", 1)[0].strip() if key_l not in ("privatekey", "publickey", "presharedkey") else val.strip()
        if section is None:
            raise ValidationError("Zeile %d steht vor [Interface]." % num)
        allowed = INTERFACE_KEYS if section == "interface" else PEER_KEYS
        if key_l not in allowed:
            cfg.removed.append(key.strip()[:30])
            continue
        if key_l in values[section]:
            if key_l in ("address", "allowedips"):
                values[section][key_l] += "," + val
                continue
            raise ValidationError("%s ist doppelt vorhanden." % allowed[key_l])
        values[section][key_l] = val

    if seen_interface != 1:
        raise ValidationError("Die Konfiguration braucht genau einen [Interface]-Abschnitt.")
    if seen_peer != 1:
        raise ValidationError("Die Konfiguration braucht genau einen [Peer]-Abschnitt (gefunden: %d)." % seen_peer)

    iface = values["interface"]
    peer = values["peer"]

    # [Interface]
    if not validate.is_wg_key(iface.get("privatekey", "")):
        raise ValidationError("PrivateKey fehlt oder ist kein gültiger WireGuard-Schlüssel (Base64, 32 Byte).")
    cfg.private_key = iface["privatekey"]
    cfg.addresses = _ipv4_list(iface.get("address", ""), "Address", cfg, interface=True)
    if not cfg.addresses:
        raise ValidationError("Address enthält keine IPv4-Adresse.")
    if "mtu" in iface:
        try:
            cfg.mtu = int(iface["mtu"])
        except ValueError:
            raise ValidationError("MTU ist keine Zahl.")
        if not 1280 <= cfg.mtu <= 1500:
            raise ValidationError("MTU muss zwischen 1280 und 1500 liegen.")

    # [Peer]
    if not validate.is_wg_key(peer.get("publickey", "")):
        raise ValidationError("PublicKey fehlt oder ist kein gültiger WireGuard-Schlüssel (Base64, 32 Byte).")
    cfg.public_key = peer["publickey"]
    if peer.get("presharedkey"):
        if not validate.is_wg_key(peer["presharedkey"]):
            raise ValidationError("PresharedKey ist kein gültiger WireGuard-Schlüssel (Base64, 32 Byte).")
        cfg.preshared_key = peer["presharedkey"]
    cfg.allowed_ips = _ipv4_list(peer.get("allowedips", ""), "AllowedIPs", cfg, interface=False)
    if not cfg.allowed_ips:
        raise ValidationError("AllowedIPs enthält kein IPv4-Netz.")
    if not peer.get("endpoint"):
        raise ValidationError("Endpoint fehlt.")
    host, port = validate.host_port(peer["endpoint"], "Endpoint")
    cfg.endpoint = "%s:%d" % (host, port)
    if "persistentkeepalive" in peer:
        ka = peer["persistentkeepalive"].lower()
        if ka == "off":
            cfg.keepalive = 0
        else:
            try:
                cfg.keepalive = int(ka)
            except ValueError:
                raise ValidationError("PersistentKeepalive ist keine Zahl.")
            if not 0 <= cfg.keepalive <= 65535:
                raise ValidationError("PersistentKeepalive muss zwischen 0 und 65535 liegen.")

    cfg.server = server_name(peer_comments, iface_comments, cfg.endpoint)
    for comment in iface_comments:
        m = _NATPMP_RE.search(comment)
        if m:
            cfg.natpmp_hint = m.group(1).lower() == "on"
    return cfg


def mtu_setting(value):
    """Validate the MTU setting of a profile: ``"conf"`` or an int 1280-1500 (also as string)."""
    if isinstance(value, str) and value.strip().lower() == "conf":
        return "conf"
    if isinstance(value, bool):
        raise ValidationError("MTU muss zwischen %d und %d liegen oder 'conf' sein." % (MTU_MIN, MTU_MAX))
    try:
        mtu = int(str(value).strip())
    except (TypeError, ValueError):
        raise ValidationError("MTU ist keine Zahl (%d bis %d oder 'aus Konfiguration')." % (MTU_MIN, MTU_MAX))
    if not MTU_MIN <= mtu <= MTU_MAX:
        raise ValidationError("MTU muss zwischen %d und %d liegen." % (MTU_MIN, MTU_MAX))
    return mtu


def profile_mtu(prof):
    """``(setting, effective MTU)`` of a profile. A profile without setting (before 0.10.3) uses ``"conf"`` if its
    wg.conf has an MTU, else the default 1340; ``"conf"`` without MTU in the file means wg-quick's 1420."""
    setting = prof.get("mtu_setting")
    if setting is None:
        setting = "conf" if prof.get("mtu") else MTU_DEFAULT
    if setting == "conf":
        return setting, int(prof.get("mtu") or MTU_AUTO)
    return setting, int(setting)


def with_mtu(conf_text, mtu):
    """The rendered config with ``MTU = mtu`` in [Interface] (an existing MTU line is replaced)."""
    out, done, section = [], False, None
    for line in conf_text.splitlines():
        low = line.strip().lower()
        if low.startswith("["):
            section = low
        if section == "[interface]" and low.replace(" ", "").startswith("mtu="):
            continue
        out.append(line)
        if section == "[interface]" and not done and low.replace(" ", "").startswith("address="):
            out.append("MTU = %d" % int(mtu))
            done = True
    if not done:
        raise ValueError("config without Address line")
    return "\n".join(out) + "\n"


def server_name(peer_comments, iface_comments, endpoint):
    """Proton writes the server (e.g. ``# CH#12``) as comment in [Peer]."""
    for comment in peer_comments + iface_comments:
        if _SERVER_RE.fullmatch(comment):
            return comment
    for comment in peer_comments:
        if comment and "=" not in comment and len(comment) <= 40 and comment.isprintable():
            return comment
    return endpoint.rsplit(":", 1)[0] if endpoint else ""


def _ipv4_list(text, what, cfg, interface):
    out = []
    for item in text.split(","):
        item = item.strip()
        if not item:
            continue
        if ":" in item:  # IPv6
            cfg.removed.append("%s %s" % (what, item[:45]))
            continue
        try:
            if interface:
                value = str(ipaddress.IPv4Interface(item if "/" in item else item + "/32"))
            else:
                value = str(ipaddress.IPv4Network(item, strict=False))
        except (ipaddress.AddressValueError, ipaddress.NetmaskValueError, ValueError):
            raise ValidationError("%s: %s ist keine gültige IPv4-Angabe." % (what, item[:45]))
        if value not in out:
            out.append(value)
    return out
