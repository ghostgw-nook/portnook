import unittest

from app import protonconf
from app.validate import ValidationError
from tests.fakes import PRIV, PROTON_SAMPLE, PSK, PUB


def conf(interface="", peer="", priv=PRIV, pub=PUB, endpoint="185.159.157.10:51820"):
    return ("[Interface]\nPrivateKey = %s\nAddress = 10.2.0.2/32\n%s\n[Peer]\nPublicKey = %s\n"
            "AllowedIPs = 0.0.0.0/0\nEndpoint = %s\n%s" % (priv, interface, pub, endpoint, peer))


class ProtonSampleTest(unittest.TestCase):
    def setUp(self):
        self.cfg = protonconf.parse(PROTON_SAMPLE)
        self.text = self.cfg.render()

    def test_rebuilt_from_allow_list(self):
        self.assertEqual(self.text, (
            "# Generated by portnook from an uploaded Proton config (allow-list)\n"
            "[Interface]\nPrivateKey = %s\nAddress = 10.2.0.2/32\n\n"
            "[Peer]\nPublicKey = %s\nAllowedIPs = 0.0.0.0/0\nEndpoint = 185.159.157.10:51820\n"
            "PersistentKeepalive = 25\n") % (PRIV, PUB))

    def test_dangerous_and_unwanted_entries_removed(self):
        for word in ("DNS", "PostUp", "PreDown", "Table", "FwMark", "SaveConfig", "curl", "rm -rf", "::", "2a07"):
            self.assertNotIn(word, self.text)
        removed = " ".join(self.cfg.removed)
        for word in ("DNS", "PostUp", "PreDown", "Table", "FwMark", "SaveConfig", "2a07:b944::2:2/128", "::/0"):
            self.assertIn(word, removed)

    def test_server_and_hints(self):
        self.assertEqual(self.cfg.server, "CH#12")
        self.assertTrue(self.cfg.natpmp_hint)
        summary = self.cfg.summary()
        self.assertNotIn(PRIV, str(summary))
        self.assertEqual(summary["endpoint"], "185.159.157.10:51820")


class ProtonValidationTest(unittest.TestCase):
    def assertRejected(self, text, fragment):
        with self.assertRaises(ValidationError) as ctx:
            protonconf.parse(text)
        self.assertIn(fragment, str(ctx.exception))
        self.assertNotIn(PRIV, str(ctx.exception))

    def test_invalid_keys(self):
        self.assertRejected(conf(priv="abc"), "PrivateKey")
        self.assertRejected(conf(priv=PRIV[:-2] + "=="), "PrivateKey")  # 31 bytes
        self.assertRejected(conf(pub="!" * 43 + "="), "PublicKey")
        self.assertRejected(conf(peer="PresharedKey = nope\n"), "PresharedKey")

    def test_optional_values(self):
        cfg = protonconf.parse(conf(interface="MTU = 1400\n", peer="PresharedKey = %s\nPersistentKeepalive = 15\n" % PSK))
        text = cfg.render()
        self.assertIn("MTU = 1400", text)
        self.assertIn("PresharedKey = %s" % PSK, text)
        self.assertIn("PersistentKeepalive = 15", text)
        self.assertRejected(conf(interface="MTU = 9000\n"), "MTU")

    def test_endpoint_and_address(self):
        self.assertRejected(conf(endpoint="1.2.3.4:51820;reboot"), "Endpoint")
        self.assertRejected(conf(endpoint="[2001:db8::1]:51820"), "IPv6")
        self.assertRejected(conf(endpoint="1.2.3.4"), "Host:Port")
        self.assertRejected(conf(endpoint="1.2.3.4:99999"), "Port")
        cfg = protonconf.parse(conf(endpoint="node-ch-12.protonvpn.net:51820"))
        self.assertEqual(cfg.endpoint, "node-ch-12.protonvpn.net:51820")
        self.assertRejected(conf().replace("10.2.0.2/32", "2a07:b944::2:2/128"), "IPv4")
        self.assertRejected(conf().replace("10.2.0.2/32", "10.2.0.300/32"), "Address")

    def test_structure(self):
        self.assertRejected("", "leer")
        self.assertRejected(conf() + "\n[Peer]\nPublicKey = %s\n" % PUB, "genau einen [Peer]")
        self.assertRejected(conf(interface="PrivateKey = %s\n" % PRIV), "doppelt")
        self.assertRejected(conf(interface="this is garbage\n"), "Zeile")
        self.assertRejected("PrivateKey = x\n" + conf(), "vor [Interface]")
        self.assertRejected(conf() + "\n[Other]\n", "Abschnitt")

    def test_case_insensitive_and_no_newline_injection(self):
        text = conf().replace("PrivateKey", "privatekey").replace("Endpoint", "ENDPOINT")
        cfg = protonconf.parse(text)
        self.assertEqual(cfg.endpoint, "185.159.157.10:51820")
        # a hook smuggled with odd spacing / casing is still dropped
        cfg = protonconf.parse(conf(interface="  postup=  iptables -F\n"))
        self.assertNotIn("iptables", cfg.render())

    def test_server_name_fallbacks(self):
        self.assertEqual(protonconf.parse(conf(peer="")).server, "185.159.157.10")
        text = conf().replace("[Peer]\n", "[Peer]\n# NL-FREE#3\n")
        self.assertEqual(protonconf.parse(text).server, "NL-FREE#3")


if __name__ == "__main__":
    unittest.main()
